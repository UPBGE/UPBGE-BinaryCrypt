/* Build-time key generator. Writes the C header holding the key of this build:
 *
 *   bc_keygen --random <out_header>              fresh key from the OS CSPRNG
 *   bc_keygen --from-file <key_file> <out_header>  fixed key (64 hex digits), for patches and DLC
 *
 * It never prints the key. The header is written to a temporary file and renamed, so an
 * interrupted build cannot leave a truncated key behind. */

#include <stdio.h>
#include <string.h>

#include "bc_key.h"
#include "bc_platform.h"

static int bc_keygen_fail(const char *message)
{
  fprintf(stderr, "bc_keygen: %s\n", message);
  return 1;
}

static bool bc_read_key_file(const char *path, uint8_t key[BC_KEY_SIZE])
{
  char text[256];
  FILE *f = bc_fopen(path, "rb");
  if (f == NULL) {
    return false;
  }
  const size_t n = fread(text, 1, sizeof(text) - 1, f);
  const bool too_long = !feof(f);
  fclose(f);
  text[n] = '\0';
  const bool ok = !too_long && bc_key_from_hex(text, key);
  crypto_wipe(text, sizeof(text));
  return ok;
}

int main(int argc, char **argv)
{
  uint8_t key[BC_KEY_SIZE];
  const char *out_path;

  if (argc == 3 && strcmp(argv[1], "--random") == 0) {
    if (!bc_random_bytes(key, sizeof(key))) {
      return bc_keygen_fail("the operating system random generator failed");
    }
    out_path = argv[2];
  }
  else if (argc == 4 && strcmp(argv[1], "--from-file") == 0) {
    if (!bc_read_key_file(argv[2], key)) {
      return bc_keygen_fail("BINARYCRYPT_KEY_FILE must contain exactly 64 hexadecimal digits");
    }
    out_path = argv[3];
  }
  else {
    return bc_keygen_fail("usage: bc_keygen --random <out> | --from-file <key_file> <out>");
  }

  char tmp_path[BC_PATH_MAX + 8];
  const int tmp_len = snprintf(tmp_path, sizeof(tmp_path), "%s.tmp", out_path);
  if (tmp_len < 0 || (size_t)tmp_len >= sizeof(tmp_path)) {
    return bc_keygen_fail("output path too long");
  }
  FILE *f = bc_fopen(tmp_path, "wb");
  if (f == NULL) {
    return bc_keygen_fail("cannot write the key header");
  }
  /* Two shares instead of the key itself (see bc_key_split): no 32 bytes of the binaries are the
   * key, so scanning them for it finds nothing. Each share sits at a random byte offset inside a
   * block of random bytes, one block in read-only data and the other in writable data, so the two
   * are neither adjacent nor aligned. */
  static uint8_t blocks[2][BC_KEY_BLOCK_SIZE + BC_KEY_SIZE];
  uint8_t shares[2][BC_KEY_SIZE];
  uint16_t offsets[2];
  if (!bc_key_split(key, shares[0], shares[1]) || !bc_random_bytes(blocks, sizeof(blocks)) ||
      !bc_random_bytes(offsets, sizeof(offsets)))
  {
    fclose(f);
    bc_remove(tmp_path);
    return bc_keygen_fail("the operating system random generator failed");
  }
  for (int s = 0; s < 2; s++) {
    offsets[s] %= BC_KEY_BLOCK_SIZE + 1;
    memcpy(blocks[s] + offsets[s], shares[s], BC_KEY_SIZE);
  }
  fputs("/* Generated by bc_keygen: the BinaryCrypt key of this build, as two shares hidden in random\n"
        " * bytes. Never commit, copy or share this file. */\n",
        f);
  fprintf(f, "#define BC_KEY_SHARE_A_OFFSET %u\n#define BC_KEY_SHARE_B_OFFSET %u\n", offsets[0], offsets[1]);
  for (int s = 0; s < 2; s++) {
    /* volatile keeps block b in writable data: never folded into read-only data next to a. */
    fprintf(f, "static %s uint8_t bc_key_block_%c[%d] = {", s ? "volatile" : "const", s ? 'b' : 'a', BC_KEY_BLOCK_SIZE + BC_KEY_SIZE);
    for (int i = 0; i < BC_KEY_BLOCK_SIZE + BC_KEY_SIZE; i++) {
      fprintf(f, "%s0x%02x", i == 0 ? "" : (i % 16) ? ", " : ",\n  ", blocks[s][i]);
    }
    fputs("};\n", f);
  }
  crypto_wipe(key, sizeof(key));
  crypto_wipe(shares, sizeof(shares));
  crypto_wipe(blocks, sizeof(blocks));
  const bool ok = fclose(f) == 0 && bc_rename_replace(tmp_path, out_path);
  if (!ok) {
    bc_remove(tmp_path);
    return bc_keygen_fail("cannot write the key header");
  }
  return 0;
}
